import { SetMetadata } from '@nestjs/common';

export enum PermissionCode {
  MANAGE_TENANT = 'MANAGE_TENANT',
  MANAGE_USERS = 'MANAGE_USERS',
  MANAGE_LANES = 'MANAGE_LANES',
  MANAGE_PRICING = 'MANAGE_PRICING',
  VIEW_BOOKINGS = 'VIEW_BOOKINGS',
  MANAGE_BOOKINGS = 'MANAGE_BOOKINGS',
  CREATE_UNPAID_HOLD = 'CREATE_UNPAID_HOLD',
  WAIVE_CANCELLATION_FEE = 'WAIVE_CANCELLATION_FEE',
  RECORD_PAYMENT = 'RECORD_PAYMENT',
  MANAGE_INVOICES = 'MANAGE_INVOICES',
  ISSUE_REFUND = 'ISSUE_REFUND',
  MANAGE_POLICIES = 'MANAGE_POLICIES',
  MANAGE_ROSTER = 'MANAGE_ROSTER',
  MANAGE_RBAC = 'MANAGE_RBAC',
  MANAGE_CUSTOMERS = 'MANAGE_CUSTOMERS',
  VIEW_CUSTOMER_PHONE = 'VIEW_CUSTOMER_PHONE',
}

export const WEB_CUSTOMER_ROLE_NAME = 'Web Customer';

export const REQUIRED_PERMISSIONS = Symbol('REQUIRED_PERMISSIONS');

export const RequirePermissions = (...permissions: PermissionCode[]) =>
  SetMetadata(REQUIRED_PERMISSIONS, permissions);
